export function detectLang(): Lang {
  // PVTA dành cho giáo viên Việt Nam: mặc định tiếng Việt dù Office đang để giao diện tiếng Anh.
  // Chỉ dùng tiếng Anh khi chủ động đặt localStorage["pvta.lang"] = "en".
  try {
    return localStorage.getItem("pvta.lang") === "en" ? "en" : "vi";
  } catch {
    return "vi";
  }
}

