// @vitest-environment jsdom
import React,{act} from 'react';
import {createRoot,type Root} from 'react-dom/client';
import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import type {ViewState} from '../src/ipc';
const mocks=vi.hoisted(()=>({rpc:vi.fn()}));
vi.mock('../src/ipc',()=>({rpc:mocks.rpc}));
import {TemplateInsertDialog,TemplateManager} from '../src/TemplateDialogs';
let host:HTMLDivElement,root:Root;
beforeEach(()=>{host=document.createElement('div');document.body.append(host);root=createRoot(host);mocks.rpc.mockReset();(HTMLDialogElement.prototype as any).showModal??=function(){this.setAttribute('open','');};(HTMLDialogElement.prototype as any).close??=function(){this.removeAttribute('open');};});
afterEach(()=>{act(()=>root.unmount());host.remove();});
const state={data:{workflowTemplates:[{id:'t1',name:'Ôn tập',params:[{key:'so-cau',label:'Số câu',required:true}],steps:[],output:{mode:'ask',text:''},createdAt:1,updatedAt:1}]}} as unknown as ViewState;
const set=(el:HTMLInputElement|HTMLTextAreaElement,v:string)=>{const proto=el instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value')!.set!.call(el,v);el.dispatchEvent(new Event('input',{bubbles:true}));};
it('imports free Markdown into an editable draft and saves only after review',async()=>{
 const onUse=vi.fn();
 const st={...state,skills:[],prompts:{own:[]},data:{...state.data,projects:[],workflowTemplates:[]}} as unknown as ViewState;
 act(()=>root.render(React.createElement(TemplateManager,{state:st,inline:true,onClose:vi.fn(),onUse,report:vi.fn(),notice:vi.fn()})));
 const click=async(text:string)=>act(async()=>[...host.querySelectorAll<HTMLButtonElement>('button')].find(b=>b.textContent===text)!.click());
 await click('Dựng từ Markdown');
 await act(async()=>set(host.querySelector('textarea')!,'# Mô tả tự do\nTạo ba mã đề.'));
 mocks.rpc.mockResolvedValueOnce({id:'draft',name:'Sinh đề',params:[],steps:[{id:'a',name:'Đọc đề',prompt:'Đọc đề nguồn.',access:'read',dependsOn:[]}],output:{mode:'fixed',text:'Ba tệp Word'}});
 await click('Phân tích bằng AI');
 expect(mocks.rpc).toHaveBeenCalledExactlyOnceWith('workflowMarkdownDraft',{text:'# Mô tả tự do\nTạo ba mã đề.'});
 expect(host.querySelector('.tpl-unsaved')).not.toBeNull();
 mocks.rpc.mockResolvedValueOnce('saved');
 await click('Lưu mẫu và tạo quy trình…');
 expect(mocks.rpc).toHaveBeenLastCalledWith('templateSave',{template:expect.objectContaining({id:'',name:'Sinh đề'})});
 expect(onUse).toHaveBeenCalledWith('saved');
});
it('keeps Markdown available to retry when AI fails',async()=>{
 const st={...state,skills:[],prompts:{own:[]},data:{...state.data,projects:[]}} as unknown as ViewState;
 act(()=>root.render(React.createElement(TemplateManager,{state:st,inline:true,markdownRequest:1,onClose:vi.fn(),onUse:vi.fn(),report:vi.fn(),notice:vi.fn()})));
 await act(async()=>set(host.querySelector('textarea')!,'Nội dung nguồn'));
 mocks.rpc.mockRejectedValueOnce(Error('AI không khả dụng'));
 await act(async()=>[...host.querySelectorAll<HTMLButtonElement>('button')].find(b=>b.textContent==='Phân tích bằng AI')!.click());
 expect(host.querySelector('[role=alert]')?.textContent).toBe('AI không khả dụng');
 expect(host.querySelector('textarea')!.value).toBe('Nội dung nguồn');
 expect(mocks.rpc).toHaveBeenCalledTimes(1);
});
it('sends parameters and the user-defined output to insert the block',async()=>{
 mocks.rpc.mockResolvedValue({kind:'plan',id:'p'});const done=vi.fn();
 act(()=>root.render(React.createElement(TemplateInsertDialog,{state,target:{planId:'p'},onClose:()=>{},onDone:done,report:vi.fn()})));
 await act(async()=>{set(host.querySelector('input[placeholder],input:not([type])') as HTMLInputElement,'12');set(host.querySelector('textarea')!,'Word 2 trang');});
 await act(async()=>{[...host.querySelectorAll('button')].find(b=>b.textContent==='Chèn')!.click();});
 expect(mocks.rpc).toHaveBeenCalledWith('templateInsert',{templateId:'t1',target:{planId:'p'},params:{'so-cau':'12'},output:'Word 2 trang'});
 expect(done).toHaveBeenCalled();
});
it('the template draft stays red after a save failure and closes only after a successful save',async()=>{
 const report=vi.fn(),notice=vi.fn();
 const managerState={...state,skills:[],prompts:{own:[]},data:{...state.data,projects:[]}} as unknown as ViewState;
 act(()=>root.render(React.createElement(TemplateManager,{state:managerState,inline:true,onClose:vi.fn(),onUse:vi.fn(),report,notice})));
 expect(host.querySelector('.tpl-saved')?.textContent).toBe('Đã lưu');
 expect(host.querySelector('.tpl-saved rect')?.getAttribute('fill')).toBe('currentColor');
 const click=async(text:string)=>act(async()=>[...host.querySelectorAll<HTMLButtonElement>('button')].find(b=>b.textContent===text)!.click());
 await click('Sửa');
 expect(host.querySelector('[role=status]')?.textContent).toBe('Đã lưu');
 const name=host.querySelector<HTMLInputElement>('.tpl-inline-editor input')!;
 await act(async()=>set(name,'Ôn tập đã sửa'));
 expect(host.querySelector('.tpl-unsaved')?.textContent).toBe('Chưa lưu');
 await act(async()=>set(name,'Ôn tập'));
 expect(host.querySelector('[role=status]')?.textContent).toBe('Đã lưu');
 await act(async()=>set(name,'Ôn tập đã sửa'));
 mocks.rpc.mockRejectedValueOnce(Error('Lưu lỗi'));
 await click('Lưu mẫu');
 expect(report).toHaveBeenCalled();expect(notice).not.toHaveBeenCalled();
 expect(host.querySelector('.tpl-unsaved')).not.toBeNull();expect(name.value).toBe('Ôn tập đã sửa');
 mocks.rpc.mockResolvedValueOnce('t1');
 await click('Lưu mẫu');
 expect(notice).toHaveBeenCalledWith('Đã lưu quy trình mẫu.');
 expect(host.querySelector('.tpl-inline-editor')).toBeNull();
});
it('the template editor offers the ! directive suggestions in the step prompt',async()=>{
 const st={...state,skills:[],prompts:{own:[]},data:{...state.data,projects:[],workflowTemplates:[{id:'t2',name:'Mẫu',params:[],steps:[{id:'a',name:'Khâu',prompt:'',access:'read'}],output:{mode:'ask',text:''},createdAt:1,updatedAt:1}]}} as unknown as ViewState;
 act(()=>root.render(React.createElement(TemplateManager,{state:st,inline:true,onClose:vi.fn(),onUse:vi.fn(),report:vi.fn(),notice:vi.fn()})));
 await act(async()=>[...host.querySelectorAll<HTMLButtonElement>('button')].find(b=>b.textContent==='Sửa')!.click());
 const ta=host.querySelector<HTMLTextAreaElement>('textarea[aria-label="Prompt của nút"]')!;
 expect(ta).not.toBeNull();
 await act(async()=>{set(ta,'!');ta.setSelectionRange(1,1);ta.dispatchEvent(new Event('select',{bubbles:true}));});
 const options=[...host.querySelectorAll('[role=option]')].map(o=>o.textContent);
 expect(options.some(t=>t!.includes('!bien'))).toBe(true);
 expect(options.some(t=>t!.includes('!ham'))).toBe(true);
 expect(host.textContent).not.toContain('Chọn tệp đầu vào');
});
